/* Phase 5: customers, staff administration, and auditable bulk imports. */

CREATE TABLE IF NOT EXISTS public.customers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_code text NOT NULL UNIQUE,
  full_name text NOT NULL,
  company_name text,
  email text,
  phone text,
  whatsapp text,
  country text,
  address text,
  notes text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.import_jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  import_type text NOT NULL CHECK (import_type IN ('parts_excel','vehicles_excel','parts_images_zip','vehicles_images_zip')),
  file_name text NOT NULL,
  status text NOT NULL DEFAULT 'processing' CHECK (status IN ('processing','completed','completed_with_errors','failed')),
  total_rows integer NOT NULL DEFAULT 0 CHECK (total_rows >= 0),
  successful_rows integer NOT NULL DEFAULT 0 CHECK (successful_rows >= 0),
  failed_rows integer NOT NULL DEFAULT 0 CHECK (failed_rows >= 0),
  created_by uuid NOT NULL REFERENCES auth.users(id),
  error_summary text,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.import_rows (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_job_id uuid NOT NULL REFERENCES public.import_jobs(id) ON DELETE CASCADE,
  row_number integer NOT NULL,
  record_key text,
  status text NOT NULL CHECK (status IN ('success','failed','skipped')),
  message text,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (import_job_id, row_number)
);

CREATE INDEX IF NOT EXISTS customers_name_idx ON public.customers (lower(full_name));
CREATE INDEX IF NOT EXISTS customers_phone_idx ON public.customers (phone);
CREATE INDEX IF NOT EXISTS import_jobs_created_idx ON public.import_jobs (created_at DESC);
CREATE INDEX IF NOT EXISTS import_rows_job_status_idx ON public.import_rows (import_job_id, status);

ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.import_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.import_rows ENABLE ROW LEVEL SECURITY;

CREATE POLICY "admin_manage_customers" ON public.customers FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());
CREATE POLICY "admin_manage_import_jobs" ON public.import_jobs FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());
CREATE POLICY "admin_manage_import_rows" ON public.import_rows FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP TRIGGER IF EXISTS set_customers_updated_at ON public.customers;
CREATE TRIGGER set_customers_updated_at BEFORE UPDATE ON public.customers
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

REVOKE ALL ON public.customers, public.import_jobs, public.import_rows FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.customers, public.import_jobs, public.import_rows TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.import_rows_id_seq TO authenticated;
